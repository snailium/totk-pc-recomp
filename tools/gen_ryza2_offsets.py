#!/usr/bin/env python3
"""Scan Ryza 2's main NSO with AOB patterns and emit ryza2_offsets.h (zero hardcoded addresses)."""
import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'recomp'))
import nso  # noqa: E402
import patches  # noqa: E402


def decode_adrp_ldr(image, off):
    w0, w1 = struct.unpack_from('<II', image, off)
    assert (w0 & 0x9f000000) == 0x90000000, f'expected adrp at +{off:#x}: {w0:08x}'
    assert (w1 & 0xffc00000) == 0xf9400000, f'expected ldr x, [x, #imm] at +{off + 4:#x}: {w1:08x}'
    immlo = (w0 >> 29) & 3
    immhi = (w0 >> 5) & 0x7ffff
    imm = (immhi << 2) | immlo
    if imm & (1 << 20):
        imm -= 1 << 21
    page = (off & ~0xfff) + (imm << 12)
    imm12 = ((w1 >> 10) & 0xfff) << 3
    return page + imm12


def scan_unique(image, text_off, text_len, pat_hex, name):
    res = patches.scan_pattern(image, text_off, text_len, patches.parse_pattern(pat_hex))
    if len(res) != 1:
        raise RuntimeError(f'ryza2_offsets: pattern {name} matched {len(res)} times (expected 1): {[hex(x) for x in res]}')
    return res[0]


def generate(main_nso_path, out_header):
    m = nso.Nso(str(main_nso_path))
    text_off, text_len = m.text

    exnow_sleep_match = scan_unique(
        m.image, text_off, text_len,
        'e00315aa??????94e00316aa??????94684e4039??????34',
        'EXNowLoading_sleep_lr',
    )
    exnow_sleep_lr = exnow_sleep_match + 16

    # Walk backwards from exnow_sleep_match to find EXNowLoading prologue: stp d11, d10, [sp, #-0x80]! (eb2bb86d)
    exnow_entry = None
    for off in range(exnow_sleep_match, max(text_off, exnow_sleep_match - 0x400), -4):
        if struct.unpack_from('<I', m.image, off)[0] == 0x6db82beb:
            exnow_entry = off
            break
    if exnow_entry is None:
        raise RuntimeError('ryza2_offsets: could not find EXNowLoading prologue')

    exnow_wait_lr = scan_unique(
        m.image, text_off, text_len,
        '68464039??????35e00314aa??????94c8060011dfe62e71',
        'EXNowLoading_wait_lr',
    ) + 16

    anim_sleep_lr = scan_unique(
        m.image, text_off, text_len,
        '41feff5406000014e00314aa??????949ca300913f031ceb',
        'anim_worker_sleep_lr',
    ) + 16

    ktgl_set_present = scan_unique(
        m.image, text_off, text_len,
        '082440b96800f837e0031f2ac0035fd6287ca10a089c2ab9',
        'ktgl_set_present_interval',
    )

    dyn_res_ref = scan_unique(
        m.image, text_off, text_len,
        '??????d0??????f9080140b91f0d0071??????541f090071',
        'dyn_res_mode_got',
    )
    dyn_res_got = decode_adrp_ldr(m.image, dyn_res_ref)

    nnmain_off = next((s[3] for s in m.exports() if s[0] == 'nnMain'), None)
    if nnmain_off is None:
        raise RuntimeError('ryza2_offsets: nnMain symbol not found in main NSO')
    app_got = decode_adrp_ldr(m.image, nnmain_off + 0x10)

    lines = [
        '// Auto-generated by tools/gen_ryza2_offsets.py from main NSO. Do not edit.',
        '#pragma once',
        '',
        f'#define RYZA2_OFF_EXNOWLOADING            {exnow_entry:#x}ull',
        f'#define RYZA2_OFF_EXNOWLOADING_SLEEP_LR   {exnow_sleep_lr:#x}ull',
        f'#define RYZA2_OFF_EXNOWLOADING_WAIT_LR    {exnow_wait_lr:#x}ull',
        f'#define RYZA2_OFF_ANIM_WORKER_SLEEP_LR    {anim_sleep_lr:#x}ull',
        f'#define RYZA2_OFF_KTGL_SET_PRESENT        {ktgl_set_present:#x}ull',
        f'#define RYZA2_OFF_APP_MAIN_LOOP           {nnmain_off:#x}ull',
        f'#define RYZA2_OFF_APP_GOT                 {app_got:#x}ull',
        f'#define RYZA2_OFF_DYN_RES_MODE_GOT        {dyn_res_got:#x}ull',
        '',
    ]
    Path(out_header).write_text('\n'.join(lines))
    return len(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('main_nso')
    ap.add_argument('out_header')
    args = ap.parse_args()
    generate(args.main_nso, args.out_header)
    print(f'wrote {args.out_header}')


if __name__ == '__main__':
    main()
